export function adminText(lang = 'pl') {
  const dict = labels[lang] || labels.pl;
  return (key, values = {}) => (dict[key] || labels.en[key] || key)
    .replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

export function adminError(error, lang, fallback = 'Save failed') {
  const t = adminText(lang);
  const message = error?.message || '';
  const missingName = /^Add a name for the (PL|EN|UA|ZH) translation\.$/.exec(message);
  if (missingName) return t('Add a name for the {lang} translation.', { lang: missingName[1] });
  return t(Object.hasOwn(labels.en, message) ? message : fallback);
}

export function adminLocale(lang) {
  return {pl:'pl-PL', en:'en-GB', ua:'uk-UA', zh:'zh-CN'}[lang] || 'pl-PL';
}

import { readFile, mkdir, writeFile, stat } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(resolve(root, 'scripts/images.json'), 'utf8'));
const desktop = [], mobile = [];
let before = 0, after = 0, mobileBytes = 0;
for (const { source, variable } of manifest) {
  const input = resolve(root, 'assets/source', source);
  before += (await stat(input)).size;
  for (const [width, suffix, target] of [[1600, '', desktop], [768, '.mobile', mobile]]) {
    const output = source.replace(/\.png$/, `${suffix}.webp`);
    const destination = resolve(root, 'public', output);
    await mkdir(dirname(destination), { recursive: true });
    await sharp(input).resize({ width, withoutEnlargement: true }).webp({ quality: 78 }).toFile(destination);
    const bytes = (await stat(destination)).size;
    if (suffix) mobileBytes += bytes; else after += bytes;
    target.push(`  ${variable}: url('/${output}');`);
  }
}
await writeFile(resolve(root, 'src/generated-images.css'), `/* Generated by npm run images. */\n:root {\n${desktop.join('\n')}\n}\n@media (max-width: 700px) {\n :root {\n${mobile.join('\n')}\n }\n}\n`);
console.log(JSON.stringify({ images: manifest.length, originalBytes: before, desktopBytes: after, mobileBytes, desktopReduction: `${((1-after/before)*100).toFixed(1)}%` }, null, 2));
